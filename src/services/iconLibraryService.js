import { supabase } from "@/lib/supabase";

/**
 * Icon library backend (shared by the logo editor and the presentation editor).
 *
 * Source of truth:
 *   - public.studio_icon_categories  → categories (is_active, sort_order)
 *   - public.studio_icons            → icons      (is_active, sort_order, category_id)
 *   - Storage bucket `eyad-icons`    → SVG files addressed by `studio_icons.storage_path`
 *
 * Categories are never discovered by scanning Storage, and nothing is hardcoded.
 */

export const ICON_BUCKET = "eyad-icons";
const MAX_SVG_BYTES = 5 * 1024 * 1024;

export class IconLibraryError extends Error {
  constructor(code, message) {
    super(message || code);
    this.name = "IconLibraryError";
    this.code = code;
  }
}

let libraryPromise = null;

/** Public URL of an icon's SVG file, generated by the existing Supabase client. */
export function getIconPublicUrl(storagePath) {
  if (!storagePath) return "";
  const { data } = supabase.storage.from(ICON_BUCKET).getPublicUrl(storagePath);
  return data?.publicUrl || "";
}

async function loadLibrary() {
  const [categoriesRes, iconsRes] = await Promise.all([
    supabase
      .from("studio_icon_categories")
      .select("id, name, slug, storage_folder, sort_order")
      .eq("is_active", true)
      .order("sort_order", { ascending: true }),
    supabase
      .from("studio_icons")
      .select("id, category_id, name, storage_path, sort_order")
      .eq("is_active", true)
      .order("sort_order", { ascending: true })
      .limit(5000),
  ]);
  if (categoriesRes.error) throw new IconLibraryError("LOAD_FAILED", categoriesRes.error.message);
  if (iconsRes.error) throw new IconLibraryError("LOAD_FAILED", iconsRes.error.message);

  const byCategory = new Map();
  (iconsRes.data || []).forEach((row) => {
    if (!row.storage_path) return;
    const icon = { id: row.id, name: row.name, storagePath: row.storage_path, url: getIconPublicUrl(row.storage_path) };
    const list = byCategory.get(row.category_id);
    if (list) list.push(icon); else byCategory.set(row.category_id, [icon]);
  });

  return (categoriesRes.data || [])
    .map((category) => ({
      id: category.id,
      name: category.name,
      slug: category.slug,
      icons: byCategory.get(category.id) || [],
    }))
    .filter((category) => category.icons.length > 0);
}

/** Active categories (sort_order ASC), each with its active icons (sort_order ASC). Cached per page load. */
export function fetchIconLibrary({ force = false } = {}) {
  if (!libraryPromise || force) {
    libraryPromise = loadLibrary().catch((error) => {
      libraryPromise = null; // allow a retry after a failure
      throw error;
    });
  }
  return libraryPromise;
}

/** Downloads an icon's SVG source text. */
export async function fetchIconSvgText(icon) {
  const url = icon?.url || getIconPublicUrl(icon?.storagePath);
  if (!url) throw new IconLibraryError("ICON_FETCH_FAILED");
  let response;
  try {
    response = await fetch(url, { mode: "cors" });
  } catch {
    throw new IconLibraryError("ICON_FETCH_FAILED");
  }
  if (!response.ok) throw new IconLibraryError("ICON_FETCH_FAILED");
  const text = await response.text();
  if (!text.trim() || text.length > MAX_SVG_BYTES) throw new IconLibraryError("ICON_FETCH_FAILED");
  return text;
}

function readIntrinsicSize(svgRoot) {
  const viewBox = (svgRoot.getAttribute("viewBox") || "").trim().split(/[ ,]+/).map(Number);
  if (viewBox.length === 4 && viewBox.every(Number.isFinite) && viewBox[2] > 0 && viewBox[3] > 0) {
    return { w: viewBox[2], h: viewBox[3], viewBox: viewBox.join(" ") };
  }
  const w = Number.parseFloat(svgRoot.getAttribute("width"));
  const h = Number.parseFloat(svgRoot.getAttribute("height"));
  if (w > 0 && h > 0) return { w, h, viewBox: `0 0 ${w} ${h}` };
  return { w: 512, h: 512, viewBox: "0 0 512 512" };
}

/**
 * Rasterises SVG source to a transparent PNG (longest side = `maxSide` px).
 * The presentation engine only embeds PNG / JPEG / GIF pictures.
 */
export async function svgToPng(svgText, maxSide = 1024) {
  if (/<!DOCTYPE|<!ENTITY/i.test(svgText)) throw new IconLibraryError("BAD_SVG");
  const doc = new DOMParser().parseFromString(svgText, "image/svg+xml");
  const root = doc.documentElement;
  if (doc.querySelector("parsererror") || !root || root.localName !== "svg") throw new IconLibraryError("BAD_SVG");

  const size = readIntrinsicSize(root);
  const scale = maxSide / Math.max(size.w, size.h);
  const width = Math.max(1, Math.round(size.w * scale));
  const height = Math.max(1, Math.round(size.h * scale));
  root.setAttribute("viewBox", size.viewBox);
  root.setAttribute("width", String(width));
  root.setAttribute("height", String(height));
  if (!root.getAttribute("xmlns")) root.setAttribute("xmlns", "http://www.w3.org/2000/svg");
  const source = new XMLSerializer().serializeToString(root);

  const blobUrl = URL.createObjectURL(new Blob([source], { type: "image/svg+xml;charset=utf-8" }));
  try {
    const image = await new Promise((resolve, reject) => {
      const img = new Image();
      img.onload = () => resolve(img);
      img.onerror = () => reject(new IconLibraryError("BAD_SVG"));
      img.src = blobUrl;
    });
    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    canvas.getContext("2d").drawImage(image, 0, 0, width, height);
    const blob = await new Promise((resolve) => canvas.toBlob(resolve, "image/png"));
    if (!blob) throw new IconLibraryError("BAD_SVG");
    return { bytes: new Uint8Array(await blob.arrayBuffer()), w: width, h: height };
  } finally {
    URL.revokeObjectURL(blobUrl);
  }
}
